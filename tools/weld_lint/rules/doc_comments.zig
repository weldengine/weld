//! Rule `doc_comments` — every root-level `pub` declaration carries a `///`,
//! and a `///` run sits against the declaration it documents.
//!
//! Normative at `engine-zig-conventions.md` §12 and §19. The doc comment is
//! required independently of the conservation criterion that arbitrates internal
//! comments: its reader is the caller, and the caller does not run the test.
//!
//! **PERIMETER — every file the linter walks, written out here rather than
//! inherited.** The rule has no path logic and takes whatever `runLint` hands
//! it: `src`, `bench`, `tests` and `tools`. That is deliberate and wider than
//! the comment rules beside it, which stop at three subtrees. A public
//! declaration in a test file has callers too — the other test files of its
//! module — so the contract its `///` carries has a reader there as well.
//!
//! **THE ORPHAN, and what is detectable.** Measured against the compiler: a
//! `///` before a container doc comment, at the end of a container body, or at
//! end of file are all compile errors, so the compiler owns them and this rule
//! would only duplicate the diagnostic. What the compiler ACCEPTS silently is a
//! `///` run separated from its declaration by a blank line or by a plain
//! comment — the doc re-attaches across the gap. That gap is the structural
//! precursor of the damaging form: insert a declaration into it and the doc
//! silently documents the newcomer while the declaration it was written for goes
//! undocumented. This rule flags the gap.
//!
//! What it does NOT reach is the damaging form itself once it has happened. A
//! doc whose text belongs to a different declaration is a question about
//! CONTENT, and no token or tree predicate expresses it; the tree holds
//! instances of it, found by comparing paragraphs against an earlier revision,
//! and they are content work rather than lint findings.
//!
//! **THE THREE SUPPRESSIONS, each with its reason, and the fourth that is the
//! scope itself.** An exemption whose reason is that some document asked for it
//! is not justified, and an unjustified one is removed rather than inherited.

const std = @import("std");
const Ast = std.zig.Ast;
const diag = @import("../diagnostic.zig");

const name = "doc_comments";

/// Hook called by `main.runLint` once per `.zig` file.
pub fn check(
    arena: std.mem.Allocator,
    file: []const u8,
    source: [:0]const u8,
    out: *std.ArrayList(diag.Diagnostic),
) !void {
    // SUPPRESSION 1 — a generated file, whole. Its shape is decided by the
    // emitter that wrote it and editing it by hand breaks a different guard, so a
    // finding here would name a defect nobody may fix in place.
    if (hasAutoGeneratedHeader(source)) return;

    var tree = try Ast.parse(arena, source, .zig);
    defer tree.deinit(arena);

    // SUPPRESSION 2 — an unparseable file, whole, and this rule is BLIND there
    // rather than deferring to something else. The reason once written here was
    // that the compiler surfaces the parse error during the normal build; that
    // holds for the 402 files inside a build closure and not for the 164 the
    // walker reaches which no target elaborates. What is true without asserting
    // anything about another mechanism: no tree, no declarations, no findings.
    if (tree.errors.len > 0) return;

    const token_tags = tree.tokens.items(.tag);
    const token_starts = tree.tokens.items(.start);

    for (tree.rootDecls()) |decl| {
        const first = tree.firstToken(decl);
        if (token_tags[first] != .keyword_pub) continue;

        if (first > 0 and token_tags[first - 1] == .doc_comment) {
            // The declaration is documented. Whether the doc SITS against it is a
            // second question: the token stream cannot tell, because the gap is
            // trivia, so the bytes are read.
            if (gapIsAdjacent(source, token_starts[first - 1], token_starts[first])) continue;
            const pos = diag.lineColFromOffset(source, token_starts[first - 1]);
            try out.append(arena, .{
                .file = file,
                .line = pos.line,
                .col = pos.col,
                .rule = name,
                .message = "`///` block detached from the declaration it documents; " ++
                    "a declaration inserted in the gap would silently take the doc",
            });
            continue;
        }

        // SUPPRESSION 3 — the two Zig entry points, per declaration. The toolchain
        // dispatches them by name and their signature carries no contract a caller
        // chooses, so a `///` would restate the language rather than the code.
        if (isEntryPoint(&tree, source, decl)) continue;

        const pos = diag.lineColFromOffset(source, token_starts[first]);
        try out.append(arena, .{
            .file = file,
            .line = pos.line,
            .col = pos.col,
            .rule = name,
            .message = "missing `///` doc comment on public declaration",
        });
    }

    // SUPPRESSION 4 — the scope. `rootDecls` is root level only, so every
    // container-internal `pub` is exempt by omission rather than by decision. The
    // tree holds 512 such declarations; making them blocking belongs to the
    // milestone that re-types those contracts anyway, and a completeness rule
    // over 512 sites produces filler.
}

/// Whether the trivia between a doc token and the declaration is a single line break.
///
/// A second line break is a blank line and a `/` opens a comment; either is an
/// insertion the compiler accepts and a reader does not see.
fn gapIsAdjacent(source: []const u8, doc_start: usize, decl_start: usize) bool {
    const line_end = std.mem.indexOfScalarPos(u8, source, doc_start, '\n') orelse return true;
    if (line_end >= decl_start) return true;
    var i = line_end + 1;
    while (i < decl_start) : (i += 1) {
        switch (source[i]) {
            ' ', '\t', '\r' => {},
            else => return false,
        }
    }
    return true;
}

fn hasAutoGeneratedHeader(source: []const u8) bool {
    if (source.len == 0) return false;
    const eol = std.mem.indexOfScalar(u8, source, '\n') orelse source.len;
    const first = source[0..eol];
    if (!std.mem.startsWith(u8, first, "//")) return false;
    return std.mem.indexOf(u8, first, "AUTO-GENERATED") != null;
}

/// Whether `decl` is `pub fn main` or `pub fn build`.
fn isEntryPoint(tree: *const Ast, source: []const u8, decl: Ast.Node.Index) bool {
    const token_tags = tree.tokens.items(.tag);
    const token_starts = tree.tokens.items(.start);
    const first = tree.firstToken(decl);

    var idx = first;
    if (idx >= token_tags.len or token_tags[idx] != .keyword_pub) return false;
    idx += 1;
    while (idx < token_tags.len) : (idx += 1) {
        switch (token_tags[idx]) {
            .keyword_inline, .keyword_noinline, .keyword_extern, .keyword_export => continue,
            else => break,
        }
    }
    if (idx >= token_tags.len or token_tags[idx] != .keyword_fn) return false;
    idx += 1;
    if (idx >= token_tags.len or token_tags[idx] != .identifier) return false;

    const start = token_starts[idx];
    // The token store carries starts only, so the identifier's end is computed.
    var end = start;
    while (end < source.len) : (end += 1) {
        const c = source[end];
        const ok = (c >= 'a' and c <= 'z') or (c >= 'A' and c <= 'Z') or (c >= '0' and c <= '9') or c == '_';
        if (!ok) break;
    }
    const name_slice = source[start..end];
    return std.mem.eql(u8, name_slice, "main") or std.mem.eql(u8, name_slice, "build");
}

fn countOn(source: [:0]const u8) !usize {
    var arena_state = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    var diags: std.ArrayList(diag.Diagnostic) = .empty;
    try check(arena, "src/x.zig", source, &diags);
    return diags.items.len;
}

/// Orphan findings only.
///
/// The two findings this rule emits are different claims, and a total counts
/// both: a fixture carrying an undocumented declaration alongside the shape
/// under test would make an orphan test pass or fail for the wrong reason.
fn countDetached(source: [:0]const u8) !usize {
    var arena_state = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    var diags: std.ArrayList(diag.Diagnostic) = .empty;
    try check(arena, "src/x.zig", source, &diags);
    var n: usize = 0;
    for (diags.items) |d| {
        if (std.mem.indexOf(u8, d.message, "detached") != null) n += 1;
    }
    return n;
}

test "a documented public declaration passes and an undocumented one fires" {
    try std.testing.expectEqual(@as(usize, 0), try countOn("/// what it is\npub const x = 1;\n"));
    try std.testing.expectEqual(@as(usize, 1), try countOn("pub const x = 1;\n"));
}

test "a blank line between a doc and its declaration is an orphan" {
    // Measured against the compiler: it ACCEPTS this and re-attaches the doc, so
    // nothing else in the build reports it.
    try std.testing.expectEqual(@as(usize, 1), try countDetached("/// what it is\n\npub const x = 1;\n"));
}

test "a plain comment between a doc and its declaration is an orphan" {
    try std.testing.expectEqual(@as(usize, 1), try countDetached("/// what it is\n// an aside\npub const x = 1;\n"));
}

test "indentation after the line break is not a gap" {
    // NON-VACUITY for the gap test: whitespace after the line break is ordinary
    // indentation, and treating it as a gap would fire on almost every file. The
    // container is documented so the only finding this fixture can produce is an
    // orphan — and the assertion is on the orphan count, not on the total, which
    // is what the first version of this test got wrong.
    try std.testing.expectEqual(@as(usize, 0), try countDetached(
        "/// the container\npub const S = struct {\n    /// what it is\n    pub const x = 1;\n};\n",
    ));
    try std.testing.expectEqual(@as(usize, 0), try countOn(
        "/// the container\npub const S = struct {\n    /// what it is\n    pub const x = 1;\n};\n",
    ));
}

test "the orphan message names the doc and not the declaration" {
    // The finding is about the block's position, so it points at the block: a
    // reader sent to the declaration would see nothing wrong there.
    var arena_state = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    var diags: std.ArrayList(diag.Diagnostic) = .empty;
    try check(arena, "src/x.zig", "/// what it is\n\npub const x = 1;\n", &diags);
    try std.testing.expectEqual(@as(usize, 1), diags.items.len);
    try std.testing.expectEqual(@as(usize, 1), diags.items[0].line);
}

test "an inserted declaration between a doc and its intended owner is NOT reported" {
    // THE BOUND, asserted rather than left to a reader. The compiler accepts this
    // and the doc re-attaches to the newcomer; whether the text belongs to it is a
    // question about content that no tree predicate expresses. Two findings come
    // out — both declarations are undocumented in the eyes of a token test — and
    // neither is the orphan.
    const src: [:0]const u8 =
        \\/// documents the second one
        \\pub const inserted = 0;
        \\pub const intended = 1;
        \\
    ;
    var arena_state = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    var diags: std.ArrayList(diag.Diagnostic) = .empty;
    try check(arena, "src/x.zig", src, &diags);
    for (diags.items) |d| {
        try std.testing.expect(std.mem.indexOf(u8, d.message, "detached") == null);
    }
}

test "the two entry points are exempt and a third function is not" {
    // NON-VACUITY on the exemption: the same shape under another name fires, so
    // the silence is about those two names and not about `pub fn` at large.
    try std.testing.expectEqual(@as(usize, 0), try countOn("pub fn main() void {}\n"));
    try std.testing.expectEqual(@as(usize, 0), try countOn("pub fn build(b: *u8) void {_ = b;}\n"));
    try std.testing.expectEqual(@as(usize, 1), try countOn("pub fn other() void {}\n"));
}

test "a generated file is exempt whole and the same source is not without the header" {
    const generated: [:0]const u8 = "// AUTO-GENERATED — DO NOT EDIT\npub const x = 1;\n";
    const plain: [:0]const u8 = "// hand written\npub const x = 1;\n";
    try std.testing.expectEqual(@as(usize, 0), try countOn(generated));
    try std.testing.expectEqual(@as(usize, 1), try countOn(plain));
}

test "an unparseable file yields no findings, and the same source parsed yields one" {
    // The suppression stated as what it is — blindness — with its counterpart, so
    // the zero is not read as a clean file.
    try std.testing.expectEqual(@as(usize, 0), try countOn("pub const x = ((( ;\n"));
    try std.testing.expectEqual(@as(usize, 1), try countOn("pub const x = 1;\n"));
}

test "a container-internal public declaration is out of scope" {
    // The fourth suppression, asserted so its removal is a visible decision.
    try std.testing.expectEqual(@as(usize, 0), try countOn(
        "/// the container\npub const S = struct {\n    pub const inner = 1;\n};\n",
    ));
}
